const fs=require('fs');
const assert=(ok,msg)=>{if(!ok)throw new Error(msg)};
const read=p=>fs.readFileSync(p,'utf8');
const pkg=JSON.parse(read('package.json'));
const release=JSON.parse(read('yb-release.json'));
const index=read('index.html');
const config=read('config.js');
const loader=read('v55-loader.js');
const sw=read('sw.js');
const manifest=JSON.parse(read('manifest.webmanifest'));
const expected=String(release.version);
assert(pkg.version===expected,`package.json version ${pkg.version} != release ${expected}`);
assert(config.includes(`APP_VERSION='${expected}'`),`config.js is not on ${expected}`);
assert(index.includes(`meta name="yb-version" content="${expected}"`),`index.html meta is not on ${expected}`);
assert(loader.includes(`const V='${expected}'`),`loader is not on ${expected}`);
assert(sw.includes(`CACHE='yurdunu-bil-v${expected}'`),`service worker cache is not on ${expected}`);
assert(String(manifest.start_url).includes(expected),`manifest start_url is not on ${expected}`);
assert(!/data-view=["']map["']/.test(index),`map navigation was reintroduced`);
assert(index.includes('v55-loader.js'),`unified loader missing`);
console.log(`release-integrity: OK (${expected})`);
